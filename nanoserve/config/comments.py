"""配置文件的注释剥离。

nano-serve 的配置文件允许 C 风格注释：``//`` 行注释和 ``/* ... */`` 块注释（块注释可跨行）。
真正解析之前先把注释去掉，只保留有效内容，并丢弃因此变空的行。
"""
from __future__ import annotations

from nanoserve._exercise import TODO, exercise


@exercise("config.strip_comments")
def strip_comments(lines: list[str]) -> list[str]:
    """去掉配置文本中的注释，返回剩下的非空行。

    规格：
      - ``lines`` 是按行切开的配置文本（每行不含换行符，可以为空串），相邻两行之间隐含一个换行。
      - 从左到右扫描，块注释外**最先出现**的注释起始符决定含义：
        * 遇到 ``//``：从这里到该行行尾的内容全部忽略（行注释内部的 ``/*`` 没有特殊含义）。
        * 遇到 ``/*``：开始块注释，直到之后第一个 ``*/`` 为止（含 ``*/`` 本身）全部忽略。
          ``*/`` 要从 ``/*`` 之后开始找，所以 ``/*/`` 并不会结束块注释。块注释内部的 ``//`` 和
          ``/*`` 没有特殊含义。
        * 块注释可以跨行，其中的换行也一并被删除：块注释开始之前的文本和 ``*/`` 之后（同一行上）
          的文本拼成**同一行**输出。
        * 块注释外单独出现的 ``*/`` 只是普通字符。没有引号 / 转义规则。
      - 去掉注释后变成空串的行不输出；行内其他字符（包括空格）一律原样保留，所以只剩空格的行要保留。
      - 保证每个块注释最终都会闭合。返回剩余行的列表，保持原有顺序。

    示例：
      >>> strip_comments(["a/*comment", "line", "more_comment*/b"])
      ['ab']
      >>> strip_comments(["port = 8080; // http", "/* tp = 2; */", "tp = 1;"])
      ['port = 8080; ', 'tp = 1;']
    """
    raise TODO("config.strip_comments")
